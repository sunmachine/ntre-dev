#!/usr/bin/env python3
"""check_valve_edits.py [--check [--base REF]] [--update-baseline] [--files FILE...] [--tagged-ok] [--verbose] [--ignore-space]

Strips the NEO conditionals from each NEO copy of a Valve source file and
compares the result with Valve's original, ignoring blank lines and leading or
trailing whitespace. Valve's files are read from git at the commit in
tools/valve-sdk-base.txt, which is fetched from Valve's repository the first time.
Run it from anywhere in the repository; it works the same on Windows and Linux.

--check is the Valve edits check that CI runs. It checks the files the current
branch changed since its merge base with REF (default origin/master, then
master), accepts lines tagged // NEO, and exits 1 when a file has more
unguarded lines than tools/valve-edits-baseline.txt allows. A count that shrank
is printed so the baseline can be lowered.

Without --check it prints "<residual line count>\t<file>" for every file that
does not round-trip, or only for --files. --update-baseline rewrites the
baseline from a run over the whole tree, with lines tagged // NEO accepted.
"""
import argparse
import difflib
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import strip_neo_ifdefs  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
SDK_BASE = os.path.join(ROOT, 'tools', 'valve-sdk-base.txt')
BASELINE = os.path.join(ROOT, 'tools', 'valve-edits-baseline.txt')
VALVE_URL = 'https://github.com/ValveSoftware/source-sdk-2013'
NEO_SYMBOLS = ['NEO', 'NEO_UNITY', 'NEO_STEAMAUDIO', 'NEO_CI_BUILD']
EXTS = {'.cpp', '.h', '.c', '.cc', '.hpp', '.inl'}
DEFAULT_BASES = ('origin/master', 'master')
BASELINE_HEADER = (
    '# Valve edits baseline: unguarded line count per Valve source file after stripping NEO conditionals.\n'
    '# Generated by python tools/neo_dev.py update-valve-baseline against tools/valve-sdk-base.txt.\n'
    '# Lines tagged // NEO do not count. A count may only shrink.\n'
    '# Format: <count><tab><path>, sorted by path.\n'
)


def git(*args, **kw):
    return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, **kw)


def fail(message):
    print(f'check_valve_edits.py: {message}', file=sys.stderr)
    sys.exit(2)


class ValveBase:
    """Valve's source files at the SDK base commit, read from git."""

    def __init__(self):
        self.sha = open(SDK_BASE).read().strip()
        if git('cat-file', '-e', f'{self.sha}^{{commit}}').returncode != 0:
            print(f'Fetching Valve base commit {self.sha[:12]}...', file=sys.stderr)
            if git('fetch', '--depth=1', VALVE_URL, self.sha).returncode != 0:
                fail(f'could not fetch {self.sha} from {VALVE_URL}')
        listing = git('ls-tree', '-r', '--name-only', '-z', self.sha, '--', 'src', check=True).stdout
        self.files = {p.decode() for p in listing.split(b'\0') if p}
        self.batch = subprocess.Popen(['git', 'cat-file', '--batch'], cwd=ROOT,
                                      stdin=subprocess.PIPE, stdout=subprocess.PIPE)

    def read(self, rel):
        if rel not in self.files:
            return None
        self.batch.stdin.write(f'{self.sha}:{rel}\n'.encode())
        self.batch.stdin.flush()
        header = self.batch.stdout.readline().split()
        size = int(header[2])
        data = self.batch.stdout.read(size)
        self.batch.stdout.read(1)
        return data


def decode(data):
    try:
        return data.decode('utf-8')
    except UnicodeDecodeError:
        return data.decode('latin-1')


def lines(text, collapse):
    out = []
    for l in text.splitlines():
        l = l.strip()
        if not l:
            continue
        if collapse:
            l = ''.join(l.split())
        out.append(l)
    return out


def strip_neo(data):
    if not data.endswith(b'\n'):
        data += b'\n'
    try:
        out, _ = strip_neo_ifdefs.resolve(data, undefined=NEO_SYMBOLS)
    except strip_neo_ifdefs.ParseError:
        return None  # an unbalanced #if
    return decode(out)


def residual(valve, neo, tagged_ok, collapse):
    stripped = strip_neo(neo)
    if stripped is None:
        return None
    a, b = lines(decode(valve), collapse), lines(stripped, collapse)
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == 'equal':
            continue
        added = b[j1:j2]
        if tagged_ok and added and all('// NEO' in l for l in added):
            continue  # tagged in-place edit: accepted
        out += [('-', l) for l in a[i1:i2]] + [('+', l) for l in added]
    return out


def changed_files(requested):
    for ref in [requested] if requested else DEFAULT_BASES:
        base = git('merge-base', ref, 'HEAD', text=True)
        if base.returncode == 0:
            out = git('diff', '--name-only', base.stdout.strip(), '--', 'src', text=True, check=True).stdout
            return out.split()
    fail(f'could not find a merge base with {requested or " or ".join(DEFAULT_BASES)}. Pass one with --base.')


def load_baseline():
    baseline = {}
    if os.path.exists(BASELINE):
        for l in open(BASELINE):
            if l.strip() and not l.startswith('#'):
                n, f = l.rstrip('\n').split('\t')
                baseline[f] = int(n)
    return baseline


def main():
    ap = argparse.ArgumentParser(description="Compare NEO's copies of Valve files with Valve's originals.")
    ap.add_argument('--check', action='store_true', help='the CI guard: changed files against the baseline')
    ap.add_argument('--base', help='with --check, the branch to compare with, default origin/master, then master')
    ap.add_argument('--update-baseline', action='store_true', help='rewrite tools/valve-edits-baseline.txt')
    ap.add_argument('--files', nargs='*', help='only these files, relative to the repository root')
    ap.add_argument('--tagged-ok', action='store_true', help='accept lines tagged // NEO')
    ap.add_argument('--verbose', action='store_true', help='print the residual lines')
    ap.add_argument('--ignore-space', action='store_true', help='also ignore whitespace changes inside a line')
    args = ap.parse_args()
    if args.check and args.update_baseline:
        fail('--check and --update-baseline do not go together.')
    if args.update_baseline and args.files is not None:
        fail('--update-baseline needs a run over the whole tree, so it does not take --files.')
    tagged_ok = args.tagged_ok or args.check or args.update_baseline
    verbose = args.verbose or args.check

    valve = ValveBase()
    if args.check:
        rels = changed_files(args.base)
    elif args.files is not None:
        rels = [f.replace('\\', '/') for f in args.files]
    else:
        rels = sorted(valve.files)
    rels = [r for r in rels if os.path.splitext(r)[1].lower() in EXTS]

    baseline = load_baseline() if args.check else {}
    counts, bad, checked = {}, 0, 0
    for rel in sorted(rels):
        path = os.path.join(ROOT, rel)
        data = valve.read(rel)
        if data is None or not os.path.exists(path):
            continue
        checked += 1
        res = residual(data, open(path, 'rb').read(), tagged_ok, args.ignore_space)
        if res is None:
            print(f'ERR\t{rel}: unbalanced conditional', file=sys.stderr)
            bad += 1
            continue
        n = len(res)
        counts[rel] = n
        if n == 0 and not args.check:
            continue
        if args.check:
            allowed = baseline.get(rel, 0)
            if n > allowed:
                print(f'::error file={rel}::unguarded edit to a Valve file: {n} lines differ, baseline allows {allowed}')
                bad += 1
            elif n < allowed:
                print(f'{rel}: {n} lines differ, baseline allows {allowed}. Lower its line in tools/valve-edits-baseline.txt'
                      + (' to:\n' + f'{n}\t{rel}' if n else ' by removing it.'))
            if n <= allowed:
                continue
        elif not args.update_baseline:
            print(f'{n}\t{rel}')
        if verbose:
            for sign, l in res:
                print(f'    {sign} {l[:140]}')

    if args.update_baseline:
        with open(BASELINE, 'w', newline='\n') as f:
            f.write(BASELINE_HEADER)
            for rel in sorted(counts):
                if counts[rel]:
                    f.write(f'{counts[rel]}\t{rel}\n')
    if args.check:
        print(f'Checked {checked} changed Valve files.')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
