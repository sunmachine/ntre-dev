#!/usr/bin/env python3
"""run_tidy.py [--build-dir DIR] [--jobs N] [--clang-tidy PATH] [--update-baseline] [PATH ...]

Runs clang-tidy over NEO-owned code and compares the findings with
tools/tidy-baseline.txt, so a pull request is only held to account for problems
it adds. The clang-tidy CI job and the CMake tidy target both run this script.

Pass one or more PATHs to analyse only those files or directories. The tree needs
a CMake configure with the unity build off, which is the linux-tooling preset. On
Windows, run this inside WSL, because clang cannot parse the Windows build.

Exit status: 0 when there is nothing new, 1 when there are new findings, 2 on an
error, such as a file clang-tidy could not parse.
"""
import argparse
import collections
import concurrent.futures
import os
import re
import shutil
import subprocess
import sys

MAJOR_VERSION = '19'
ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
BASELINE = os.path.join(ROOT, 'tools', 'tidy-baseline.txt')
COMPILE_DB_TOOL = os.path.join(ROOT, 'tools', 'tidy_compile_db.py')
DEFAULT_PRESET = 'linux-tooling'

# The directories that carry a .clang-tidy with checks switched on.
NEO_DIRS = (
    'src/game/client/neo/',
    'src/game/server/neo/',
    'src/game/shared/neo/',
    'src/common/neo/',
    'src/tests/',
)

# Passed on the command line, because findings in NEO headers are dropped when
# this filter is only set in .clang-tidy. It starts at /src/ so that a checkout
# in a directory named neo does not match every Valve header.
HEADER_FILTER = '/src/(game/(client|server|shared)/neo|common/neo|tests)/'

BASELINE_HEADER = """\
# clang-tidy baseline: findings per file and check that CI accepts for now.
# Generated by tools/run_tidy.py --update-baseline from the linux-tooling preset.
# Counts instead of line numbers, so unrelated edits do not invalidate an entry.
# A count may only shrink. Fix a finding, then regenerate this file.
# Format: <count><tab><check><tab><path>, sorted by path.
"""

FINDING =re.compile(r'^(.+?):(\d+):(\d+): (?:warning|error): (.*) \[([\w.,-]+)\]$')
# Anchored, because clang-tidy also echoes source lines, which can contain any text.
ERROR = re.compile(r'^(.+:\d+:\d+: )?(fatal )?error: ')


def fail(message):
    print(f'run_tidy.py: {message}', file=sys.stderr)
    sys.exit(2)


def find_clang_tidy(requested):
    names = [requested] if requested else [f'clang-tidy-{MAJOR_VERSION}', 'clang-tidy']
    for name in names:
        binary = shutil.which(name)
        if not binary:
            continue
        output = subprocess.run([binary, '--version'], capture_output=True, text=True).stdout
        found = re.search(r'version (\d+)\.', output)
        if found and found.group(1) == MAJOR_VERSION:
            return binary
        fail(f'{binary} is not version {MAJOR_VERSION}.')
    fail(f'clang-tidy {MAJOR_VERSION} was not found. See Code style in CONTRIBUTING.md.')


def repo_path(path):
    return os.path.relpath(os.path.realpath(path), ROOT).replace(os.sep, '/')


def prepare_compile_db(build_dir):
    if not os.path.exists(os.path.join(build_dir, 'compile_commands.json')):
        fail(f'{build_dir} has no compile_commands.json. Run: cmake --preset {DEFAULT_PRESET} in src')
    out_dir = os.path.join(build_dir, 'tidy-db')
    subprocess.run([sys.executable, '-I', COMPILE_DB_TOOL, build_dir, out_dir], check=True, stdout=subprocess.DEVNULL)
    with open(os.path.join(out_dir, 'files.txt')) as f:
        files = f.read().splitlines()
    if any('/Unity/' in f for f in files):
        fail(f'{build_dir} is a unity build. Run: cmake --preset {DEFAULT_PRESET} in src, and use that build directory')
    return out_dir, files


def select_files(files, paths):
    selected = [f for f in files if f.startswith(NEO_DIRS)]
    if paths:
        wanted = [repo_path(p) for p in paths]
        selected = [f for f in selected if any(f == w or f.startswith(w + '/') for w in wanted)]
    if not selected:
        fail('no NEO-owned file in the compile database matches.')
    return selected


def analyse(clang_tidy, compile_db, path):
    result = subprocess.run(
        [clang_tidy, '-p', compile_db, '-quiet', f'--header-filter={HEADER_FILTER}', path],
        cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors='replace',
    )
    return path, result.returncode, result.stdout


def run_all(clang_tidy, compile_db, files, jobs):
    # Keyed by location, since a finding in a header repeats for every file that
    # includes it.
    findings = {}
    errors = []
    with concurrent.futures.ThreadPoolExecutor(jobs) as pool:
        tasks = [pool.submit(analyse, clang_tidy, compile_db, f) for f in files]
        for done, task in enumerate(concurrent.futures.as_completed(tasks), 1):
            path, returncode, output = task.result()
            print(f'[{done}/{len(files)}] {path}', flush=True)
            file_errors = []
            for line in output.splitlines():
                match = FINDING.match(line)
                if match and 'clang-diagnostic-error' not in match.group(5):
                    key = (repo_path(match.group(1)), int(match.group(2)), int(match.group(3)), match.group(5))
                    findings[key] = match.group(4)
                elif ERROR.search(line):
                    file_errors.append(line)
            if file_errors or returncode != 0:
                errors.append((path, returncode, file_errors))
    return findings, errors


def load_baseline():
    baseline = {}
    if os.path.exists(BASELINE):
        with open(BASELINE) as f:
            for line in f:
                if line.strip() and not line.startswith('#'):
                    count, check, path = line.rstrip('\n').split('\t')
                    baseline[(path, check)] = int(count)
    return baseline


def write_baseline(counts):
    with open(BASELINE, 'w', newline='\n') as f:
        f.write(BASELINE_HEADER)
        for (path, check), count in sorted(counts.items()):
            f.write(f'{count}\t{check}\t{path}\n')


def report_new(findings, counts, baseline):
    new_keys = sorted(k for k, count in counts.items() if count > baseline.get(k, 0))
    if not new_keys:
        return False
    print('\nNew findings. The baseline cannot tell which location is new, so every location in the group is listed.')
    for path, check in new_keys:
        print(f'\n{path}: {check}: {counts[(path, check)]} found, baseline allows {baseline.get((path, check), 0)}')
        for (file, line, column, tag), message in sorted(findings.items()):
            if (file, tag) == (path, check):
                print(f'  {file}:{line}:{column}: {message}')
    message = f'clang-tidy reported new findings in {len(new_keys)} file and check groups. Each is listed above.'
    print(f'::error::{message}' if os.environ.get('GITHUB_ACTIONS') else f'\n{message}')
    return True


def main():
    parser = argparse.ArgumentParser(description='Run clang-tidy over NEO-owned code and compare with the baseline.')
    parser.add_argument('paths', nargs='*', metavar='PATH', help='analyse only these files or directories')
    parser.add_argument('--build-dir', default=os.path.join(ROOT, 'src', 'build', DEFAULT_PRESET))
    parser.add_argument('--jobs', type=int, default=os.cpu_count() or 4)
    parser.add_argument('--clang-tidy', help='path to clang-tidy, default clang-tidy-19, then clang-tidy')
    parser.add_argument('--update-baseline', action='store_true', help='rewrite tools/tidy-baseline.txt from this run')
    args = parser.parse_args()
    if os.name == 'nt':
        fail('on Windows, run this inside WSL. See Code style in CONTRIBUTING.md.')
    if args.update_baseline and args.paths:
        fail('--update-baseline needs a run over the whole tree, so it does not take a PATH.')

    clang_tidy = find_clang_tidy(args.clang_tidy)
    compile_db, all_files = prepare_compile_db(os.path.abspath(args.build_dir))
    files = select_files(all_files, args.paths)
    findings, errors = run_all(clang_tidy, compile_db, files, args.jobs)

    if errors:
        print('\nclang-tidy could not analyse these files, so the results are incomplete:')
        for path, returncode, lines in sorted(errors):
            print(f'  {path}: exit status {returncode}')
            for line in lines[:5]:
                print(f'    {line}')
        sys.exit(2)

    counts = collections.Counter((path, tag) for path, _, _, tag in findings)
    if args.update_baseline:
        write_baseline(counts)
        print(f'\nWrote {sum(counts.values())} findings to {repo_path(BASELINE)}.')
        return

    baseline = load_baseline()
    has_new = report_new(findings, counts, baseline)
    print(f'\n{sum(counts.values())} findings in {len(files)} files.')
    if not args.paths:
        fixed = sum(n - counts.get(k, 0) for k, n in baseline.items() if n > counts.get(k, 0))
        if fixed:
            print(f'{fixed} baseline findings are gone. Run tools/run_tidy.py --update-baseline to lower the counts.')
    sys.exit(1 if has_new else 0)


if __name__ == '__main__':
    main()
